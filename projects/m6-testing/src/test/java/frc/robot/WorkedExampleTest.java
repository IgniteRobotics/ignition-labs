package frc.robot;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.ctre.phoenix6.controls.VelocityVoltage;
import frc.robot.plant.LaunchProfile;
import frc.robot.plant.ShooterFlywheel;
import frc.robot.support.PhoenixTestSupport;
import org.junit.jupiter.api.Test;

/**
 * The worked example. Read it, then write your own.
 *
 * <p>This is the only test in this project that was written for you. Everything else in {@code
 * src/test/} is yours, and three good tests beat an abandoned attempt at full coverage.
 *
 * <p><b>Do not edit this file.</b> It is covered by {@code tests.lock}; a pull request that changes
 * it fails CI with a message inviting you to disagree in review instead.
 */
class WorkedExampleTest {

  /**
   * A pure-logic test. No hardware, no simulation, no setup — construct the thing, call the method,
   * assert the answer.
   *
   * <p>Three things here are worth copying into your own tests:
   *
   * <ol>
   *   <li><b>The name says what is being claimed.</b> Not {@code test1}. When this fails in CI six
   *       weeks from now, the name is the first thing anyone reads.
   *   <li><b>The expected value was worked out by hand, not by running the code.</b> 4096 ticks at
   *       2048 ticks per revolution is two motor revolutions; at a 4:1 reduction that is half a
   *       mechanism revolution. If you compute the expectation the same way the code does, you have
   *       written a test that agrees with any bug the code contains.
   *   <li><b>The tolerance argument is not optional.</b> {@code assertEquals(0.5, actual)} on
   *       doubles compares exact bit patterns and fails on floating-point noise. That is M1's
   *       lesson arriving in test form, and it is the single most common way a correct test is
   *       written wrong.
   * </ol>
   */
  @Test
  void ticksToMechanismRotations_appliesBothTicksPerRevolutionAndGearRatio() {
    LaunchProfile profile = new LaunchProfile(2048.0, 4.0);

    assertEquals(0.5, profile.ticksToMechanismRotations(4096.0), 1e-9);
  }

  /**
   * A simulated-hardware test, and the reason {@link ShooterFlywheel} implements {@link
   * AutoCloseable}.
   *
   * <p>The try-with-resources block is the pattern to copy. A simulated device holds its CAN ID
   * until it is closed, so a second test that constructs a flywheel on ID 1 fails unless this one
   * tore its own down — and it tears down even if an assertion throws, which a {@code close()} call
   * at the end of the method would not.
   *
   * <p>Note what is asserted and what is not. {@code getAppliedControl()} is the device object's
   * own record of the last control request your code gave it — a local, in-process value, set the
   * instant {@code setControl()} is called, not something read back over simulated CAN — so
   * checking it proves <b>your {@code setVelocity()} call issued the exact control request you
   * intended</b>. It does not prove the request reached the device, and it does not assert that the
   * simulated motor spins up to exactly that velocity, because that would be testing whether CTRE's
   * physics model behaves the way CTRE says it does — which tests CTRE, not you. If your assertion
   * would pass regardless of what you wrote, you have not tested your code: an assertion that only
   * checked the velocity <i>signal's</i> status code, for example, would still pass even if {@code
   * setVelocity()} never called {@code setControl()} at all, because that signal reports OK
   * independent of whether a command was ever issued.
   */
  @Test
  void shooterFlywheel_acceptsAControlRequest_andClosesCleanly() {
    PhoenixTestSupport.enableRobot();

    try (ShooterFlywheel flywheel = new ShooterFlywheel(1)) {
      PhoenixTestSupport.settleAfterConstruction(flywheel.motor());

      flywheel.motor().getSimState().setSupplyVoltage(12.0);
      flywheel.setVelocity(20.0);
      PhoenixTestSupport.settleAfterControlRequest(flywheel.motor());

      Object appliedControl = flywheel.motor().getAppliedControl();
      assertTrue(
          appliedControl instanceof VelocityVoltage,
          "The flywheel's last applied control request is not a VelocityVoltage. Either "
              + "setVelocity() never called setControl(), or it sent the wrong kind of "
              + "request.");
      assertEquals(20.0, ((VelocityVoltage) appliedControl).Velocity, 1e-9);
    }
  }
}
